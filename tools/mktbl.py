"""Generate tbl/jp.tbl (16-bit little-endian codes; table keys are the two bytes in ROM order).

    python -X utf8 tools/mktbl.py [--kanji tbl/kanji.tsv] > tbl/jp.tbl

Rows (docs/re/text.md): code = JIS row-1 cell - 0x20 for symbols (0x01-0x5E), digits 0xC0-0xC9, A-Z 0xD1-0xEA,
a-z 0xF1-0x10A, hiragana ぁ-ん 0x111-0x163, katakana ァ-ヶ 0x171-0x1C6, 0x400 = …. Kanji codes (0x20-0x2F, 0x60-0xBF,
0x1C8-0x4FF) have no fixed order: they come from tbl/kanji.tsv (code<TAB>char) once identified; unknown codes decode
as hex escapes, which keeps decode -> encode byte-exact. Control codes are per engine and live in the extractor.
"""
import sys

ROW1 = '　、。，．・：；？！゛゜´｀¨＾￣＿ヽヾゝゞ〃仝々〆〇ー―‐／＼～∥｜…‥‘’“”（）〔〕［］｛｝〈〉《》「」『』【】＋－±×÷＝≠＜＞≦≧∞∴♂♀°′″℃￥＄￠￡％＃＆＊＠§☆★○●◎◇'


def rows():
    out = []
    # 0x0000 is a full-width space in dialogue and the terminator in menus: left to the extractor.
    for i, ch in enumerate(ROW1, 1):
        out.append((i, ch))
    out += [(0x1C, '―'), (0x1D, 'ー')]  # the script writes the long vowel as 0x1D (JIS ―); later entries win
    for i in range(10):
        out.append((0xC0 + i, chr(0xFF10 + i)))
    for i in range(26):
        out.append((0xD1 + i, chr(0xFF21 + i)))
        out.append((0xF1 + i, chr(0xFF41 + i)))
    for i, c in enumerate(range(0x3041, 0x3094)):
        out.append((0x111 + i, chr(c)))
    for i, c in enumerate(range(0x30A1, 0x30F7)):
        out.append((0x171 + i, chr(c)))
    out.append((0x400, '‥'))  # two-dot leader glyph; shown as …… pairs in text
    return out


def main():
    ents = dict(rows())
    if '--kanji' in sys.argv:
        path = sys.argv[sys.argv.index('--kanji') + 1]
        for line in open(path, encoding='utf-8'):
            if line.strip() and not line.startswith('#'):
                code, ch = line.rstrip('\n').split('\t')[:2]
                ents[int(code, 16)] = ch
    print('# Bounty Sword main font, 16-bit LE codes. Generated by tools/mktbl.py; do not edit by hand.')
    for code in sorted(ents):
        print('%02X%02X=%s' % (code & 0xFF, code >> 8, ents[code]))


if __name__ == '__main__':
    main()
